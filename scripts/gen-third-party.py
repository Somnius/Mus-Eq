"""Regenerates docs/THIRD_PARTY.md from Cargo.lock (via cargo metadata) and web/node_modules.

Run from the repository root after `npm ci` in web/:  python3 scripts/gen-third-party.py
The licence strings are what each package declares; this script does not read licence texts.
"""
import json, subprocess, os, collections

meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--locked"], text=True))
rust = sorted({(p["name"], p["version"], p.get("license") or "NOT DECLARED")
               for p in meta["packages"] if p.get("source")})
counts = collections.Counter(l for _, _, l in rust)

web = []
pj = json.load(open("web/package.json"))
for name in sorted({**pj.get("dependencies", {}), **pj.get("devDependencies", {})}):
    f = os.path.join("web/node_modules", name, "package.json")
    if os.path.exists(f):
        d = json.load(open(f))
        lic = d.get("license") or d.get("licenses") or "NOT DECLARED"
        web.append((name, d.get("version", "?"), lic if isinstance(lic, str) else json.dumps(lic)))

out = []
w = out.append
w("# Third-party software\n")
w("Mus-Eq's own code is MIT OR Apache-2.0 (see the licence files in the repository root). It builds on the")
w("software below. The licence of each package is the one it **declares** in its own metadata; this list was")
w("generated by `scripts/gen-third-party.py` and the licence texts themselves were not re-read. Check a")
w("package's own LICENSE file before relying on a line here.\n")
w("## Rust crates (everything in `Cargo.lock`, including build and test tools)\n")
w(f"{len(rust)} packages. By declared licence:\n")
for lic, n in counts.most_common():
    w(f"- {n} x `{lic}`")
w("\nNotes:\n")
w("- **symphonia** (decoders, 16 crates) is MPL-2.0. MPL-2.0 applies per file: Mus-Eq links the crates unchanged, and")
w("  anyone shipping a binary has to keep their notices and be able to point to the unmodified source, which is the")
w("  crates published at the versions in `Cargo.lock`. None of the checked source files carries the licence's")
w("  \"Incompatible With Secondary Licenses\" notice (checked for symphonia 0.6.1, `.rs` files only).")
w("- **rusty-chromaprint** declares MIT. Its README says it is a port of Chromaprint, whose own source is MIT and which")
w("  bundles some LGPL-2.1 FFmpeg code; the port uses the `rustfft` and `rubato` crates instead, and its source never")
w("  mentions FFmpeg. That is evidence, not a legal conclusion.")
w("- **libopus** is compiled from source by the `opus` crate. Its licence (BSD-3-Clause upstream) was not re-checked here.")
w("- **zip** (unpacks the downloaded deno `.zip`) and **lzma-sys** (used by `xz2` to unpack the downloaded `.tar.xz`) compiles the C source of the xz/liblzma library into the")
w("  server. That library's own licence (public domain or 0BSD upstream) was not checked here.")
w("- Two crates offer `MIT OR Apache-2.0 OR LGPL-2.1-or-later`; Mus-Eq takes the MIT or Apache-2.0 option.\n")
w("<details><summary>Full Rust list</summary>\n")
w("| Package | Version | Declared licence |\n|---|---|---|")
for n, v, l in rust:
    w(f"| {n} | {v} | {l} |")
w("\n</details>\n")
w("## Web client (direct dependencies only)\n")
w("| Package | Version | Declared licence |\n|---|---|---|")
for n, v, l in web:
    w(f"| {n} | {v} | {l} |")
w("\nTransitive npm packages are not listed here. Classic Winamp skins (`.wsz`) are supplied by the user and belong to")
w("their authors; none are shipped.\n")
w("## Android app (declared in `android/app/build.gradle.kts`)\n")
w("AndroidX Media3 (ExoPlayer, session, datasource), AndroidX Core, Guava (through Media3) and Kotlin. These are")
w("understood to be Apache-2.0 but that was **not** checked against their published metadata; `org.json` and JUnit")
w("are used only in the unit tests. A Gradle licence report has not been generated yet.\n")
w("## Other\n")
w("- **ffmpeg**, **yt-dlp** and **deno** are not shipped, in the repository or in the container image. The server downloads them")
w("  on request after a typed confirmation, from addresses and SHA-256 values pinned in `crates/museq-server/src/tools.rs`")
w("  (see \"Programs Mus-Eq downloads\" in the README). They run as separate programs, not linked into Mus-Eq.")
w("  - ffmpeg n8.1.3: a build by the BtbN project (`autobuild-2026-10-31-12-59`, the `lgpl` variant). It is configured")
w("    with `--enable-version3` and without `--enable-gpl`, which makes it LGPL-3.0-or-later; that wording follows")
w("    FFmpeg's published rules and was only partly checked against ffmpeg.org/legal.html.")
w("  - yt-dlp 2026.10.26: Unlicense. The single-file Linux build also bundles Python and other components under their")
w("    own licences, which have not been reviewed here.")
w("  - deno 2.9.8: MIT (checked in the project's LICENSE.md). yt-dlp's own documentation says it needs a JavaScript")
w("    runtime for full YouTube support and recommends deno; Mus-Eq downloads deno on request and points yt-dlp at it.")
w("  - Whoever downloads them receives them under those licences; Mus-Eq does not redistribute them.")
w("- **Radio station list**: Tray-FM by Constantinos (Unlicense), `data/stations/trayfm-stations.txt`.")
open("docs/THIRD_PARTY.md", "w").write("\n".join(out) + "\n")
print("wrote docs/THIRD_PARTY.md:", len(rust), "rust,", len(web), "web")
